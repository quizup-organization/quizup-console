-- Console d'exploitation Axon : état courant (dernière ingestion d'agent) + audit des actions.
-- Volontairement sans table d'historique : les timelines viennent de Prometheus (métriques
-- `quizup.axon.console.*` exposées par l'agent SDK).

CREATE TABLE console_instance
(
    id             bigint generated by default as identity,
    application    varchar(255)                not null,
    instance_id    varchar(255)                not null,
    version        varchar(255),
    uptime_seconds bigint                      not null,
    first_seen     timestamp(6) with time zone not null,
    last_seen      timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_console_instance unique (application, instance_id)
);

CREATE TABLE console_processor
(
    id             bigint generated by default as identity,
    application    varchar(255)                not null,
    instance_id    varchar(255)                not null,
    name           varchar(255)                not null,
    mode           varchar(64)                 not null,
    running        boolean                     not null,
    error          boolean                     not null,
    replaying      boolean                     not null,
    supports_reset boolean                     not null,
    updated_at     timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_console_processor unique (application, instance_id, name)
);

CREATE TABLE console_segment
(
    id               bigint generated by default as identity,
    application      varchar(255) not null,
    instance_id      varchar(255) not null,
    processor        varchar(255) not null,
    segment_id       integer      not null,
    mask             integer      not null,
    caught_up        boolean      not null,
    replaying        boolean      not null,
    merging          boolean      not null,
    error_state      boolean      not null,
    current_position bigint,
    reset_position   bigint,
    error_type       varchar(512),
    error_message    varchar(1024),
    primary key (id),
    constraint uk_console_segment unique (application, instance_id, processor, segment_id)
);

CREATE TABLE console_dlq_stat
(
    id          bigint generated by default as identity,
    application varchar(255)                not null,
    instance_id varchar(255)                not null,
    processor   varchar(255)                not null,
    size        bigint                      not null,
    sequences   bigint                      not null,
    updated_at  timestamp(6) with time zone not null,
    primary key (id),
    constraint uk_console_dlq_stat unique (application, instance_id, processor)
);

CREATE TABLE console_audit
(
    id          bigint generated by default as identity,
    occurred_at timestamp(6) with time zone not null,
    actor       varchar(255),
    action      varchar(64)                 not null,
    application varchar(255),
    instance_id varchar(255),
    target      varchar(512),
    parameters  text,
    result      varchar(32)                 not null,
    error       varchar(1024),
    primary key (id)
);

CREATE INDEX idx_console_processor_app ON console_processor (application, name);
CREATE INDEX idx_console_audit_occurred_at ON console_audit (occurred_at);
